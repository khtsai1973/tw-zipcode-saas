CITY_ROAD_DISTRICT: dict[str, dict[str, str]] = {
    "基隆市": _KEELUNG,
    "新竹市": _HSINCHU,
    "嘉義市": _CHIAYI,
}


def infer_district(city: str | None, road: str | None) -> str | None:
    """依縣市 + 路名推論行政區（僅基隆／新竹／嘉義）。"""
    if not city or not road:
        return None
    table = CITY_ROAD_DISTRICT.get(city)
    if not table:
        return None

    # 精確 → 去段 → 最長前綴
    if road in table:
        return table[road]

    base = re.sub(r"[一二三四五六七八九十百零\d]+段$", "", road)
    if base != road and base in table:
        return table[base]

    # 最長路名前綴命中（例如 光復路二段101巷 → 已在 parser 拆路）
    best_key = ""
    best_dist = None
    for key, dist in table.items():
        if road.startswith(key) and len(key) > len(best_key):
            best_key = key
            best_dist = dist
    return best_dist
